#!/usr/bin/env python3
# Turn a corpus-roundtrip.sh TSV (typeid<TAB>typename<TAB>status<TAB>reason) into docs/reference/COVERAGE.md.
#   tools/coverage-report.py <results.tsv> <scope-description> > docs/reference/COVERAGE.md
import sys, collections

results, scope = sys.argv[1], sys.argv[2]
per = collections.defaultdict(lambda: {"total":0,"exact":0,"fail":0,"missing":0,"name":"","reasons":collections.Counter()})
for line in open(results):
    parts = line.rstrip("\n").split("\t")
    if len(parts) < 3: continue
    tid, name, status = parts[0], parts[1], parts[2]
    reason = parts[3] if len(parts) > 3 else ""
    d = per[tid]; d["total"] += 1; d[status] = d.get(status,0)+1
    if name and not d["name"]: d["name"] = name
    if status == "fail" and reason: d["reasons"][reason] += 1

rows = sorted(per.items(), key=lambda kv: -kv[1]["total"])
tot = sum(d["total"] for _,d in rows); ex = sum(d["exact"] for _,d in rows)
pct = (100.0*ex/tot) if tot else 0.0

print("# Coverage matrix\n")
print("Byte-exact round-trip coverage per asset type, measured by `tools/corpus-roundtrip.sh` "
      "(compile → decompile → recompile → compare instance/relocation/import bytes).\n")
print(f"**Scope:** {scope}\n")
print(f"**Overall:** {ex}/{tot} assets byte-exact (**{pct:.1f}%**) across {len(rows)} asset types.\n")
print("A type is only counted byte-exact if its decompiled XML recompiled to *identical* bytes. "
      "`fail`/`missing` are honest gaps, not crashes. Art/W3D/texture/particle types are expected to lag — "
      "they belong to the art pipeline (roadmap #3), not the data decompiler.\n")
print("| Type | TypeId | Total | Byte-exact | % | Top failure reason |")
print("|------|--------|------:|-----------:|--:|--------------------|")
for tid, d in rows:
    p = (100.0*d["exact"]/d["total"]) if d["total"] else 0.0
    top = d["reasons"].most_common(1)[0][0] if d["reasons"] else ("—" if d["exact"]==d["total"] else "")
    name = d["name"] or "(unknown)"
    print(f"| {name} | 0x{tid} | {d['total']} | {d['exact']} | {p:.0f}% | {top} |")
print("\n_Generated by `tools/coverage-report.py` from `tools/corpus-roundtrip.sh` output. "
      "Regenerate after changes; this file is a measurement, not a promise._")
